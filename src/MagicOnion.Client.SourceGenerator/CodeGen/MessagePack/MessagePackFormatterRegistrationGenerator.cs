using MagicOnion.Client.SourceGenerator.CodeAnalysis;

namespace MagicOnion.Client.SourceGenerator.CodeGen.MessagePack;

internal class MessagePackFormatterRegistrationGenerator : ISerializerFormatterGenerator
{
    public (string HintNameSuffix, string Source) Build(GenerationContext generationContext, SerializationFormatterCodeGenContext ctx)
    {
        using var pooledStringBuilder = generationContext.GetPooledStringBuilder();
        var writer = pooledStringBuilder.Instance;
        var hasNamespace = !string.IsNullOrEmpty(generationContext.Namespace);
        var indent = hasNamespace ? "    " : string.Empty;

        writer.AppendLine("""
            // <auto-generated />
            #pragma warning disable

            """);

        if (hasNamespace)
        {
            writer.AppendLineWithFormat($$"""
            namespace {{generationContext.Namespace}}
            {
            """);
        }

        writer.AppendLineWithFormat($$"""
            {{indent}}partial class {{generationContext.InitializerPartialTypeName}}
            {{indent}}{
            #if UNITY_2022_3_OR_NEWER
            {{indent}}    [global::UnityEngine.RuntimeInitializeOnLoadMethod(global::UnityEngine.RuntimeInitializeLoadType.SubsystemRegistration)]
            #elif NET5_0_OR_GREATER
            {{indent}}    [global::System.Runtime.CompilerServices.ModuleInitializer]
            #endif
            {{indent}}    internal static void RegisterMessagePackFormatters()
            {{indent}}    {
            {{indent}}        var registry = global::MessagePack.SourceGeneratedFormatterFactory.Instance;
            """);
        foreach (var registration in ctx.FormatterRegistrations)
        {
            if (registration is EnumSerializationInfo)
            {
                writer.AppendLineWithFormat($$"""
                {{indent}}        registry.RegisterHarvested<{{registration.FullName}}>(new global::MessagePack.Formatters.EnumFormatterFactory<{{registration.FullName}}>());
                """);
            }
            else
            {
                if (registration.FormatterName.StartsWith("global::MessagePack.Formatters.InterfaceReadOnlySetFormatterFactory", StringComparison.Ordinal))
                {
                    writer.AppendLine("#if NET9_0_OR_GREATER");
                }
                writer.AppendLineWithFormat($$"""
                {{indent}}        registry.RegisterHarvested<{{registration.FullName}}>(new {{registration.FormatterName}}{{registration.FormatterConstructorArgs}});
                """);
                if (registration.FormatterName.StartsWith("global::MessagePack.Formatters.InterfaceReadOnlySetFormatterFactory", StringComparison.Ordinal))
                {
                    writer.AppendLine("#endif");
                }
            }
        }
        writer.AppendLineWithFormat($$"""
            {{indent}}    }
            {{indent}}}
            """);

        if (hasNamespace)
        {
            writer.AppendLine("}");
        }

        return (".MessagePack", writer.ToString());
    }
}
